import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
const config = JSON.parse(readFileSync('src-tauri/tauri.conf.json','utf8'));
const schema = JSON.parse(readFileSync('node_modules/@tauri-apps/cli/config.schema.json','utf8'));
const capability = JSON.parse(readFileSync('src-tauri/capabilities/default.json','utf8'));
const pkg = JSON.parse(readFileSync('package.json','utf8'));
const lock = JSON.parse(readFileSync('package-lock.json','utf8'));
const cargo = readFileSync('src-tauri/Cargo.toml','utf8');
const rustVersion = cargo.match(/^version\s*=\s*"([^"]+)"/m)?.[1];
assert.equal(pkg.version, '0.3.0', 'Expected Sprint 03 version');
assert.equal(config.version, pkg.version, 'Tauri/npm versions must match');
assert.equal(lock.version, pkg.version, 'Lockfile version must match');
assert.equal(lock.packages[''].version, pkg.version);
assert.equal(rustVersion, pkg.version, 'Rust/npm versions must match');
for (const icon of config.bundle.icon ?? []) assert.ok(existsSync(resolve('src-tauri',icon)), 'Missing icon: ' + icon);
assert.equal(config.$schema,'https://schema.tauri.app/config/2');
assert.ok(pkg.dependencies['@tauri-apps/api'].includes('2'));
for (const key of Object.keys(config)) assert.ok(key === '$schema' || key in schema.properties, 'Campo Tauri desconhecido: ' + key);
assert.equal(config.build.beforeBuildCommand,'npm run build');
assert.ok(existsSync(resolve('src-tauri',config.build.frontendDist,'index.html')),'Execute o build frontend primeiro');
assert.ok(config.bundle.active && config.bundle.targets.includes('nsis'));
assert.ok(config.app.windows.some(w => (w.label ?? 'main') === 'main'));
assert.ok(capability.windows.includes('main'));
assert.ok(capability.permissions.includes('core:window:allow-destroy'));
assert.ok(!capability.permissions.some(p => typeof p !== 'string' || p.startsWith('fs:')),'Filesystem deve permanecer restrito ao backend');
console.log('Configuração Tauri 2: estrutura, caminhos de build, NSIS e capability principal conferidos. Validação Rust/ACL completa depende de cargo build.');
